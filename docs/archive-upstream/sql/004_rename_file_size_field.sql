-- 1. 重命名文件大小字段
ALTER TABLE files RENAME COLUMN size TO size_bytes;

-- 2. 验证修改
SELECT
    COUNT(*) as total_files,
    AVG(size_bytes) as avg_size,
    MAX(size_bytes) as max_size,
    MIN(size_bytes) as min_size
FROM files;

