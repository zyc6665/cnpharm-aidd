@pytest.mark.asyncio
async def test_non_molecule_table_artifacts_are_untouched(db_session: AsyncSession, owner: User):
    record = await store_file_bytes(
        db_session,
        content=b"CCO\n",
        filename="anything.txt",
        content_type="text/plain",
        source_type=FileSourceType.TOOL_OUTPUT,
        owner_id=owner.id,
        project_id=None,
    )
    artifact = ParsedStandardArtifact(
        output_name="report",
        type="run_report@1",
        name="report",
        files={},
    )
    updated = await normalize_molecule_table_files(
        db_session,
        task=SimpleNamespace(user_id=owner.id),  # type: ignore[arg-type]
        project_id="project-1",
        artifact=artifact,
        resolved_files=[("report_json", record)],
    )
    assert updated == [("report_json", record)]


