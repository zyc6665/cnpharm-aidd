def _artifact(metadata: dict | None = None) -> ParsedStandardArtifact:
    return ParsedStandardArtifact(
        output_name="molecules",
        type="molecule_table@1",
        name="molecules",
        files={},
        metadata=metadata or {},
    )


def test_headerless_smiles_list_is_detected():
    assert is_headerless_smiles_table("CCO\nNC(N)=O\n") is True


def test_table_with_comma_header_is_left_alone():
    assert is_headerless_smiles_table("smiles,name\nCCO,ethanol\n") is False


def test_tab_separated_header_is_left_alone():
    assert is_headerless_smiles_table("smiles\tname\nCCO\tethanol\n") is False


def test_single_header_token_is_left_alone():
    assert is_headerless_smiles_table("smiles\nCCO\n") is False


def test_to_smiles_csv_adds_header_and_skips_noise():
    text = "# generated by pocket2mol\nCCO\n\nNC(N)=O extra-column\n"
    csv_text = to_smiles_csv(text)
    assert csv_text.splitlines() == ["smiles", "CCO", "NC(N)=O"]


def test_smiles_rows_keeps_first_column_only():
    assert smiles_rows("CCO ethanol\nNC(N)=O urea\n") == ["CCO", "NC(N)=O"]


def test_csv_filename_swaps_suffix():
    assert csv_filename("SMILES.txt") == "SMILES.csv"
    assert csv_filename("molecules") == "molecules.csv"


@pytest.mark.asyncio
async def test_normalization_replaces_primary_file_with_csv(db_session: AsyncSession, owner: User):
    legacy = await store_file_bytes(
        db_session,
        content=b"CCO\nNC(N)=O\n",
        filename="SMILES.txt",
        content_type="text/plain",
        source_type=FileSourceType.TOOL_OUTPUT,
        owner_id=owner.id,
        project_id=None,
    )
    task = SimpleNamespace(user_id=owner.id)

    updated = await normalize_molecule_table_files(
        db_session,
        task=task,  # type: ignore[arg-type]
        project_id="project-1",
        artifact=_artifact({"molecule_id_field": "smiles"}),
        resolved_files=[("table_file", legacy), ("metadata_json", legacy)],
    )

    normalized = dict(updated)["table_file"]
    assert normalized.id != legacy.id
    assert normalized.filename == "SMILES.csv"
    assert normalized.content_type == "text/csv"
    assert normalized.file_meta["normalization"] == "headerless-smiles-to-csv"
    assert normalized.file_meta["normalized_from_file_id"] == str(legacy.id)
    # 其它角色原样保留
    assert dict(updated)["metadata_json"] is legacy


